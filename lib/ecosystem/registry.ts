export function getDomainRecord(hostname: string): EcosystemDomainRecord | undefined {
  const normalized = hostname.toLowerCase().trim()
  return ECOSYSTEM_DOMAINS.find(
    (d) => d.hostname === normalized || d.canonicalHostname === normalized
  )
}

export function getBrandDomains(brandSlug: string): EcosystemDomainRecord[] {
  return ECOSYSTEM_DOMAINS.filter((d) => d.brandSlug === brandSlug)
}
